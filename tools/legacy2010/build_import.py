def split_vals(s):
    out=[];i=0;n=len(s)
    while i<n:
        if s[i]=="'":
            j=i+1;buf=[]
            while True:
                if s[j]=="'" and j+1<n and s[j+1]=="'": buf.append("'"); j+=2; continue
                if s[j]=="'": break
                buf.append(s[j]); j+=1
            out.append(('s',''.join(buf), s[i:j+1])); i=j+1
        else:
            j=s.find(',',i); j=n if j<0 else j
            tok=s[i:j].strip(); out.append(('n',tok,tok)); i=j
        while i<n and s[i] in ', ': i+=1
    return out
def load(p):
    rows=collections.defaultdict(list)
    for m in ROW.finditer(open(p,encoding='utf-8').read()):
        cols=[c.strip() for c in m.group(2).split(',')]
        rows[m.group(1)].append((cols, split_vals(m.group(3)), m.group(0)))
    return rows
